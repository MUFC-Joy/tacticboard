/* 取某队主帅（找不到返回空串，由调用方决定兜底） */
window.tbCoachOf = function(team){
  var c = window.TB_COACHES && window.TB_COACHES[team];
  return c && c.n ? c.n : "";
};
/* 待核对清单：[{team,coach,st,src}]，只返回 st!=='ok' 的队 */
window.tbCoachPending = function(){
  var out = [];
  var all = window.TB_COACHES || {};
  Object.keys(all).forEach(function(t){
    var c = all[t];
    if (c.st !== "ok") out.push({ team:t, coach:c.n || "", st:c.st, src:c.src || "", since:c.since || "" });
  });
  return out;
};
